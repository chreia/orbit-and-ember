/** Every interface string: the first-pass keys above and the later ones in i18n.extra.ts. */
export type TKey = Key | ExtraKey;

const EN: Record<TKey, string> = { ...en, ...enExtra };
// Patwa falls back to English wherever an entry is missing
const DICTS: Record<Lang, Partial<Record<TKey, string>>> = {
  en: EN,
  es: { ...es, ...esExtra },
  jam: { ...jam, ...jamExtra },
};

export type T = (key: TKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICTS[lang];
  return (key, vars) => {
    let s = d[key] || EN[key] || key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
    return s;
  };
}

/** Number and date formats; Patwa readers get Jamaican English formats. */
export const LOCALE: Record<Lang, string> = { en: 'en-US', es: 'es-AR', jam: 'en-JM' };

export interface I18n {
  lang: Lang;
  t: T;
  locale: string;
  /** integer with grouping */
  fmt: (x: number, digits?: number) => string;
  /** compact form for small cells: 1.2k */
  fmtCompact: (x: number) => string;
  monthShort: (month: number) => string;
  monthLong: (month: number) => string;
  /** "Mar 2020" for a month index label */
  monthYear: (year: number, month: number) => string;
}

export function makeI18n(lang: Lang): I18n {
  const locale = LOCALE[lang];
  const nf0 = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });
  const nf1 = new Intl.NumberFormat(locale, { maximumFractionDigits: 1 });
  const nfc = new Intl.NumberFormat(locale, { notation: 'compact', maximumFractionDigits: 1 });
  const short = new Intl.DateTimeFormat(locale, { month: 'short', timeZone: 'UTC' });
  const long = new Intl.DateTimeFormat(locale, { month: 'long', timeZone: 'UTC' });
  const my = new Intl.DateTimeFormat(locale, { month: 'short', year: 'numeric', timeZone: 'UTC' });
  const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1).replace(/\.$/, '');
  const monthShort = Array.from({ length: 12 }, (_, i) => cap(short.format(Date.UTC(2001, i, 15))));
  const monthLong = Array.from({ length: 12 }, (_, i) => cap(long.format(Date.UTC(2001, i, 15))));
  return {
    lang,
    t: makeT(lang),
    locale,
    fmt: (x, digits) => {
      if (!Number.isFinite(x)) return '–';
      if (digits !== undefined) {
        // round first so tiny negatives do not print as "-0.0"
        const r = Number(x.toFixed(digits)) || 0;
        return new Intl.NumberFormat(locale, { maximumFractionDigits: digits, minimumFractionDigits: digits }).format(r);
      }
      return Math.abs(x) < 10 && x !== Math.round(x) ? nf1.format(x) : nf0.format(x);
    },
    fmtCompact: (x) => {
      if (!Number.isFinite(x)) return '';
      if (x === 0) return '0';
      if (x < 10) return nf1.format(x);
      return x < 1000 ? nf0.format(x) : nfc.format(x);
    },
    monthShort: (m) => monthShort[m - 1],
    monthLong: (m) => monthLong[m - 1],
    monthYear: (y, m) => cap(my.format(Date.UTC(y, m - 1, 15))),
  };
}

export const I18nContext = createContext<I18n>(makeI18n('en'));
export const useI18n = () => useContext(I18nContext);

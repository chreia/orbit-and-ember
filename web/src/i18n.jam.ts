// Jamaican Patwa (jam) interface strings. Same keys and order as `en` in i18n.tsx.
//
// Spelling: everyday English-based Patwa as written on social media and in newspaper
// columns, not the Cassidy-JLU orthography. One spelling per word:
//   di (the), dis (this), dat (that), dese (these), dem (they, them, their; also the plural
//   marker after a noun: "di month dem"), den (then), dan (than), deh (there, is located),
//   wid (with), widout (without), togedda (together), odda (other), tru (through),
//   inna (in), pon (on), ova (over), unda (under), round (around), bout (about, roughly),
//   fi (for; "to" before a verb), a (of: "di number a hotspot"; also the copula before a
//   noun and the progressive marker: "Data a load"), an (and), weh (relative who/which/
//   where), wah (interrogative what), wen (when), seh (that, after verbs of saying),
//   nuh (not, before a verb or adjective), neva (did not; "Neva observe" = not observed),
//   cyaan (cannot), couldn (could not), haffi (have to), woulda / shoulda (would / should
//   have), a go (future "will"), wi (we), yuh (you, your), mi (I), mek (make), tek (take),
//   lef (leave), nutten (nothing), ting (thing), yah so (right here), likkle (little).
//   Other th- words keep English spelling (three, thick). "Burn", never "bun".
//   Write "a 80% interval" and "a extreme month": "an" is reserved for "and".
//
// Grammar: verbs take no -s or -ed ("It jump wen VIIRS join"). Nouns take no English -s
// plural: a number or quantifier marks it ("12 month", "{n} hotspot"), or "dem" after the
// noun for a definite plural. Past is the bare verb; "did" marks past state.
//
// Terms kept in English (Jamaicans code-mix technical words): hotspot, detection, sensor,
// satellite, cell, grid, region, province, period, record, harmonized, baseline, median,
// z, interval, anomaly, model estimate, terrain, scale, ratio, series, CSV, PNG, WebGL,
// and every proper name (NASA, FIRMS, MODIS, VIIRS, S-NPP, NOAA-20, Terra, Aqua, Focos,
// Space Apps, Blue Marble, place names).
//
// Term choices:
//   naive merge          -> straight add-up
//   far above normal     -> way above normal
//   not observed         -> neva observe
//   observed, none       -> observe, nutten detect
//   partial month / year -> month / year nuh complete
//   anomalous            -> unusual
//   synthetic (data)     -> mek-up
//   image                -> picture
//   annual               -> yearly
//   selected period      -> period yuh pick
//   custom area          -> yuh own area
//   mean (average)       -> average

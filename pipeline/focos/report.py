"""Write docs/results.md and the README results block from the bundle's validation.json.

No number in the docs is typed by hand.

    python -m focos.report --bundle web/public/data
"""
from __future__ import annotations

import argparse
import json
import re

LABEL = {"none": "No harmonization", "ratio": "National ratio", "ratio_local": "Local ratio",
         "gbm": "Transfer model", "blend": "Blend"}
TEST = {"loyo": "Leave one year out (2012-2017)", "backcast": "Backcast (train 2015-17, predict 2012-14)",
        "loro": "Leave one region out", "forward": "Forward (train 2012-17, predict 2018-21)"}


def pick(rows, **kw):
    out = [r for r in rows if all(r.get(k) == v for k, v in kw.items())]
    return out[0] if out else None


def fmt(v, d=2, pct=False):
    if v is None:
        return "n/a"
    return f"{v:+.0f}%" if pct else f"{v:.{d}f}"


def table(rows, variant, test, level, calendar=True):
    head = "| Method | Log error | Bias | Rank corr. |" + (" Season shape | Peak month | Anomaly class |" if calendar else "")
    sep = "|---|---|---|---|" + ("---|---|---|" if calendar else "")
    lines = [head, sep]
    for m in ("none", "ratio", "ratio_local", "gbm", "blend"):
        r = pick(rows, variant=variant, test=test, level=level, method=m)
        if not r:
            continue
        line = f"| {LABEL[m]} | {fmt(r['log_rmse'])} | {fmt(r['bias_pct'], pct=True)} | {fmt(r['spearman'])} |"
        if calendar:
            line += f" {fmt(r.get('season_r'))} | {fmt(r.get('peak_match'))} | {fmt(r.get('anomaly_agreement'))} |"
        lines.append(line)
    return "\n".join(lines)


def build(v: dict, manifest: dict) -> tuple[str, str]:
    rows = v["metrics"]
    chosen = v["chosen_method"]
    an = v["annual_national"]
    yrs = an["years"]
    i11, i12 = yrs.index(2011), yrs.index(2012)
    naive_jump = an["naive_merge"][i12] / max(an["naive_merge"][i11], 1)
    harm_jump = an["harmonized"][i12] / max(an["harmonized"][i11], 1)
    modis_jump = an["modis_only"][i12] / max(an["modis_only"][i11], 1)
    rby = v["ratio_by_year"]
    cov = v["uncertainty"]["coverage80"]
    best = pick(rows, variant="terra_aqua", test="backcast", level="province-month", method=chosen)
    base = pick(rows, variant="terra_aqua", test="backcast", level="province-month", method="none")
    ratio = pick(rows, variant="terra_aqua", test="backcast", level="province-month", method="ratio")

    md = ["# Results", "",
          "Generated by `python -m focos.report` from `web/public/data/validation.json`. Every score is "
          "computed on data the method did not see. Method and tests: [METHODS.md](METHODS.md).", "",
          "## The sensors disagree", "",
          f"Over 2012 to 2025, VIIRS S-NPP counted between {min(rby['viirs_per_modis']):.1f} and "
          f"{max(rby['viirs_per_modis']):.1f} times as many hotspots as MODIS Terra and Aqua together, year by year. "
          f"NOAA-20 counts {v['noaa20_per_snpp']:.3f} times S-NPP on days both observed.", "",
          "| Province | VIIRS per MODIS hotspot, 2012-2017 | MODIS hotspots |", "|---|---|---|"]
    rbp = [r for r in v["ratio_by_province"] if r["n_modis"] >= 500]
    for r in rbp:
        md.append(f"| {r['name']} | {r['viirs_per_modis']:.2f} | {r['n_modis']:,} |")
    md += ["", f"Provinces with at least 500 MODIS hotspots in 2012-2017. The ratio runs from "
           f"{rbp[-1]['viirs_per_modis']:.1f} to {rbp[0]['viirs_per_modis']:.1f}, so one national factor cannot "
           "convert one record into the other everywhere.", ""]
    md += ["## Held-out accuracy", ""]
    for test in ("backcast", "loyo", "loro", "forward"):
        md += [f"### {TEST[test]}", "", "Province-months:", "", table(rows, "terra_aqua", test, "province-month"), "",
               "0.1 degree cells by month:", "", table(rows, "terra_aqua", test, "cell-month", calendar=False), ""]
    md += ["### Terra only (November 2000 to June 2002)", "",
           table(rows, "terra_only", "backcast", "province-month"), ""]
    md += ["## Continuity of the record", "",
           "| Year | Naive merge | MODIS only | Harmonized | 80% interval |", "|---|---|---|---|---|"]
    for j, y in enumerate(yrs):
        lo, hi = an["harmonized_lo"][j], an["harmonized_hi"][j]
        iv = f"{lo:,.0f} to {hi:,.0f}" if hi > lo else "observed"
        md.append(f"| {y} | {an['naive_merge'][j]:,.0f} | {an['modis_only'][j]:,.0f} | {an['harmonized'][j]:,.0f} | {iv} |")
    md += ["", f"From 2011 to 2012 a naive merge of every FIRMS sensor rises {naive_jump:.1f}-fold because VIIRS "
           f"begins. The harmonized record changes by {100 * (harm_jump - 1):+.0f}%, in line with MODIS on its own "
           f"({100 * (modis_jump - 1):+.0f}%), so the sensor step is gone.", "",
           "## Uncertainty", "",
           f"The 80% interval for model months covers {100 * cov['backcast']:.0f}% of held-out region-months in the "
           f"backcast test and {100 * cov['loyo']:.0f}% in leave one year out.", ""]
    gb = pick(rows, variant="terra_aqua", test="loyo", level="province-month", method=chosen)
    md += [f"The transfer model undercounts slightly on held-out years (total bias {gb['bias_pct']:+.0f}% leaving "
           f"one year out, {best['bias_pct']:+.0f}% in the backcast), so reconstructed years before 2012 may read a "
           "few percent low; the interval is built from those same held-out errors.", ""]
    md += ["## Sensor outages detected", "", "| Sensor | Days not observing | Longest gap |", "|---|---|---|"]
    for s, runs in v["outages"].items():
        if not runs:
            md.append(f"| {s} | 0 | none |")
            continue
        import datetime as dt
        lens = [(dt.date.fromisoformat(b) - dt.date.fromisoformat(a)).days + 1 for a, b in runs]
        k = max(range(len(runs)), key=lambda i: lens[i])
        md.append(f"| {s} | {sum(lens)} | {runs[k][0]} to {runs[k][1]} |")
    md.append("")

    headline = (
        f"- In the backcast test (train 2015 to 2017, reconstruct 2012 to 2014 from MODIS alone), the "
        f"{LABEL[chosen].lower()} reaches a province-month log error of {best['log_rmse']:.2f} and a total bias "
        f"of {best['bias_pct']:+.0f}%, against {base['log_rmse']:.2f} and {base['bias_pct']:+.0f}% with no "
        f"harmonization and {ratio['log_rmse']:.2f} and {ratio['bias_pct']:+.0f}% with one national ratio.\n"
        f"- It picks the same peak month as VIIRS in {100 * (best.get('peak_match') or 0):.0f}% of province-years and "
        f"the same anomaly class in {100 * (best.get('anomaly_agreement') or 0):.0f}% of province-months.\n"
        f"- From 2011 to 2012 a naive merge of all FIRMS sensors jumps {naive_jump:.1f}-fold because VIIRS begins; "
        f"the harmonized record changes by {100 * (harm_jump - 1):+.0f}%, in line with MODIS alone "
        f"({100 * (modis_jump - 1):+.0f}%).\n"
        f"- The 80% interval on reconstructed months covers {100 * cov['backcast']:.0f}% of held-out region-months."
    )
    return "\n".join(md), headline


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", default="web/public/data")
    ap.add_argument("--readme", default="README.md")
    ap.add_argument("--out", default="docs/results.md")
    a = ap.parse_args()
    with open(f"{a.bundle}/validation.json") as f:
        v = json.load(f)
    with open(f"{a.bundle}/manifest.json") as f:
        m = json.load(f)
    md, headline = build(v, m)
    with open(a.out, "w") as f:
        f.write(md + "\n")
    with open(a.readme) as f:
        txt = f.read()
    txt = re.sub(r"(<!-- results:start -->\n).*?(<!-- results:end -->)",
                 lambda mm: mm.group(1) + headline + "\n" + mm.group(2), txt, flags=re.DOTALL)
    with open(a.readme, "w") as f:
        f.write(txt)
    print(headline)


if __name__ == "__main__":
    main()
